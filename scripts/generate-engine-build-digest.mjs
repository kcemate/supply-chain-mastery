import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePaths = ['src/engine/canonical.ts', 'src/engine/simulator.ts', 'src/flywayEngine.ts', 'src/flywayTypes.ts'];
const outputPath = resolve(root, 'src/engine/buildDigest.generated.ts');

async function digest() {
  const hash = createHash('sha256');
  for (const path of sourcePaths) {
    hash.update(path);
    hash.update('\0');
    hash.update(await readFile(resolve(root, path)));
    hash.update('\0');
  }
  return hash.digest('hex');
}

const value = await digest();
const generated = `// Generated by scripts/generate-engine-build-digest.mjs. Do not edit manually.\nexport const ENGINE_BUILD_DIGEST = '${value}';\n`;
if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8');
  if (current !== generated) {
    console.error('Engine build digest is stale. Run: node scripts/generate-engine-build-digest.mjs --write');
    process.exitCode = 1;
  }
} else if (process.argv.includes('--write')) {
  await writeFile(outputPath, generated);
} else {
  process.stdout.write(`${value}\n`);
}
